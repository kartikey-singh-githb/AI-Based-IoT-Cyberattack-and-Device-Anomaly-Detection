class DatasetError(Exception):
    """Raised when a dataset cannot be located or parsed."""


def list_datasets() -> List[DatasetEntry]:
    return list(REGISTRY.values())


def get_dataset(dataset_id: str) -> DatasetEntry:
    entry = REGISTRY.get(dataset_id)
    if entry is None:
        raise DatasetError(
            f"Unknown dataset '{dataset_id}'. Supported: "
            f"{', '.join(REGISTRY)}"
        )
    return entry


def resolve_path(reference: str) -> Path:
    """Resolve a dataset id, a bare filename or a filesystem path."""
    if reference in REGISTRY:
        return REGISTRY[reference].path

    candidate = Path(reference)
    if candidate.is_absolute():
        if candidate.exists():
            return candidate
        raise DatasetError(f"File not found: {candidate}")

    for base in (DEFAULT_DATASET_DIR, Path.cwd(), PROJECT_DIR):
        p = base / reference
        if p.exists():
            return p

    raise DatasetError(
        f"Dataset file '{reference}' not found. Place it under "
        f"{DEFAULT_DATASET_DIR} or pass an absolute path."
    )


def load_frame(reference: str, *, limit_rows: Optional[int] = None
               ) -> Tuple[pd.DataFrame, DatasetEntry]:
    """Load a CSV into a DataFrame plus its registry metadata."""
    path = resolve_path(reference)
    entry = REGISTRY.get(reference) or _entry_for_path(path)

    try:
        frame = pd.read_csv(path)
    except Exception as exc:
        raise DatasetError(f"Could not read CSV {path}: {exc}") from exc

    if frame.empty:
        raise DatasetError(f"Dataset {path} contains no rows")
    if limit_rows:
        frame = frame.head(limit_rows)

    log.info("Loaded dataset %s: %d rows x %d columns",
             path.name, frame.shape[0], frame.shape[1])
    return frame, entry


def _entry_for_path(path: Path) -> DatasetEntry:
    for entry in REGISTRY.values():
        if entry.path.resolve() == path.resolve():
            return entry
    return DatasetEntry(
        id=path.stem,
        name=path.name,
        kind="public" if "synthetic" not in path.stem else "synthetic",
        description="User-supplied CSV loaded from disk.",
        source="local file",
        download_page="",
        license="Unknown - supplied by the operator.",
        format="CSV",
        features=", ".join(str(c) for c in pd.read_csv(path, nrows=0).columns),
        preprocessing="Applied automatically by the trainer.",
        filename=path.name,
        notes="Not part of the built-in registry.",
    )


def detect_label_column(frame: pd.DataFrame) -> Optional[str]:
    for candidate in LABEL_COLUMN_CANDIDATES:
        if candidate in frame.columns:
            return candidate
    lowered = {str(c).lower(): str(c) for c in frame.columns}
    for candidate in LABEL_COLUMN_CANDIDATES:
        if candidate.lower() in lowered:
            return lowered[candidate.lower()]
    return None


def is_telemetry_shaped(frame: pd.DataFrame) -> bool:
    """True when the CSV exposes the streaming sensor columns."""
    columns = {str(c).lower() for c in frame.columns}
    sensor_hits = len(columns & {"temperature", "humidity", "energy_w",
                                 "voltage", "current_a", "rssi"})
    return sensor_hits >= 2


def prepare_dataset_matrix(
    frame: pd.DataFrame,
    *,
    label_column: Optional[str] = None,
    max_features: int = 60,
) -> Tuple[pd.DataFrame, Optional[pd.Series], List[str]]:
    """Build a clean numeric matrix for offline (``dataset`` space) training.

    Returns ``(X, y, used_columns)``.  *y* is ``None`` when no usable label
    column exists, which is what keeps evaluation metrics honest: they are
    only reported when ground truth is genuinely present.
    """
    data = frame.copy()

    y: Optional[pd.Series] = None
    if label_column:
        if label_column not in data.columns:
            raise DatasetError(f"Label column '{label_column}' not present")
        y = data[label_column]
        data = data.drop(columns=[label_column])

    drop = [c for c in data.columns if str(c).lower() in NON_FEATURE_COLUMNS]
    data = data.drop(columns=drop, errors="ignore")

    numeric = data.select_dtypes(include="number")
    # Remove constant columns and obvious identifiers (unique per row).
    numeric = numeric.loc[:, numeric.nunique(dropna=True) > 1]
    numeric = numeric.replace([float("inf"), float("-inf")], pd.NA)

    if numeric.shape[1] == 0:
        raise DatasetError("No usable numeric feature columns found")

    # Keep the most variable columns when the dataset is very wide.
    if numeric.shape[1] > max_features:
        variance = numeric.var(numeric_only=True).sort_values(ascending=False)
        keep = list(variance.head(max_features).index)
        numeric = numeric[keep]

    medians = numeric.median(numeric_only=True)
    numeric = numeric.fillna(medians).fillna(0.0)

    if y is not None:
        # Map arbitrary labels onto binary normal/attack for evaluation.
        y_bin = y.astype(str).str.lower().isin(
            {"normal", "benign", "0", "legit", "legitimate", "false"}
        ).map({True: 0, False: 1})
        # If everything collapsed to one class there is no ground truth.
        if y_bin.nunique() < 2:
            y_bin = None
        y = y_bin

    return numeric, y, list(numeric.columns)
