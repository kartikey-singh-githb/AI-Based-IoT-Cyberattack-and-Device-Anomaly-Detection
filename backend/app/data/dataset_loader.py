"""Dataset registry and loader.

The registry documents each supported dataset *before* it is used: source,
download page, licence/usage conditions, format, relevant features and the
preprocessing this project applies.  Files are never downloaded automatically
- the user places a CSV under ``data/datasets/`` and the loader picks it up.

Two families are supported:

``synthetic``  generated by :mod:`app.data.synthetic`, always available and
               clearly labelled as simulated demo data.

``public``     reputable IoT intrusion-detection datasets the user may
               download manually (see docs/dataset_guide.md).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import pandas as pd

from app.core.logging_config import get_logger
from app.core.config import PROJECT_DIR

log = get_logger("dataset_loader")

DEFAULT_DATASET_DIR = PROJECT_DIR / "data" / "datasets"

# File extensions the loader understands.  The format is chosen from the
# suffix; no content sniffing or implicit conversions are performed.
SUPPORTED_FORMATS = {
    ".csv": "csv",
    ".parquet": "parquet",
    ".pq": "parquet",
}

# Column names that never become model input.
NON_FEATURE_COLUMNS = {
    "label", "labels", "target", "class", "attack", "attack_class",
    "attack_cat", "attack_type", "category", "type", "device_id", "deviceid",
    "id", "row_id", "rowid", "record_id", "flow_id", "flow id", "flowid",
    "index", "unnamed: 0", "timestamp", "time", "ts", "src_ip", "dst_ip",
    "srcip", "dstip", "source", "label_encoded",
}

LABEL_COLUMN_CANDIDATES = [
    "label", "labels", "target", "class", "attack", "category", "Attack",
    "Label", "CLASS", "type",
]

DEFAULT_SAMPLE_SEED = 42


@dataclass
class DatasetEntry:
    id: str
    name: str
    kind: str                       # synthetic | public
    description: str
    source: str
    download_page: str
    license: str
    format: str
    features: str
    preprocessing: str
    filename: str                   # expected file inside data/datasets/
    notes: str = ""
    extra: Dict[str, str] = field(default_factory=dict)

    @property
    def path(self) -> Path:
        return DEFAULT_DATASET_DIR / self.filename

    @property
    def available(self) -> bool:
        return self.path.exists()

    def rows(self) -> Optional[int]:
        if not self.available:
            return None
        try:
            if _format_for_path(self.path) == "parquet":
                return _parquet_metadata(self.path)[0]
            with self.path.open("rb") as fh:
                return max(0, sum(1 for _ in fh) - 1)
        except (OSError, DatasetError):
            return None

    def size_bytes(self) -> Optional[int]:
        try:
            return self.path.stat().st_size if self.available else None
        except OSError:
            return None


