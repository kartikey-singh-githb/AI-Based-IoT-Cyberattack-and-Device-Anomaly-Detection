"""Dataset registry and loader.

The registry documents each supported dataset *before* it is used: source,
download page, licence/usage conditions, format, relevant features and the
preprocessing this project applies.  Files are never downloaded automatically
- the user places a CSV under ``data/datasets/`` and the loader picks it up.

Two families are supported:

``synthetic``  generated by :mod:`app.data.synthetic`, always available and
               clearly labelled as simulated demo data.

``public``     reputable IoT intrusion-detection datasets the user may
               download manually (see docs/dataset_guide.md).
"""

